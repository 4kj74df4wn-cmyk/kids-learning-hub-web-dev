const CHILD_COPY_PATTERNS = [
  [/ลองโจทย์ใหม่ด้วยตัวเอง\s*(\d+)\s*\/\s*(\d+)/g,'ข้อ $1 จาก $2 • ลองคิดด้วยตัวเอง'],
  [/ลองโจทย์ใหม่\s*(\d+)\s*\/\s*(\d+)/g,'ข้อ $1 จาก $2 • ลองคิดด้วยตัวเอง'],
  [/ข้อ\s*(\d+)\s*\/\s*(\d+)/g,'ข้อ $1 จาก $2'],
  [/ทำเองได้:\s*(\d+)%/g,'ทำเองได้ $1%']
];

function isDevOnly(node){
  const el=node.nodeType===1?node:node.parentElement;
  return !!(el&&el.closest&&el.closest('#telemetry,.devdetails,.devtools,.devbox'));
}

function rewriteChildText(root=document.body){
  if(!root)return;
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  const nodes=[];
  while(walker.nextNode())nodes.push(walker.currentNode);
  for(const node of nodes){
    if(isDevOnly(node))continue;
    const before=node.nodeValue;
    let after=before;
    for(const [from,to] of CHILD_COPY_REPLACEMENTS){
      if(after.includes(from))after=after.split(from).join(to);
    }
    for(const [pattern,to] of CHILD_COPY_PATTERNS)after=after.replace(pattern,to);
    if(after!==before)node.nodeValue=after;
  }
}

let copyScheduled=false;
function scheduleCopyRewrite(){
  if(copyScheduled)return;
  copyScheduled=true;
  queueMicrotask(()=>{copyScheduled=false;rewriteChildText(document.body);});
}

const childCopyObserver=new MutationObserver(scheduleCopyRewrite);
childCopyObserver.observe(document.documentElement,{subtree:true,childList:true,characterData:true});
rewriteChildText(document.body);
